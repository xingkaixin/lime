//go:build ignore

// gen_pierre builds pierre_gen.go and copies the used SVGs from Pierre Icons
// (https://github.com/pierrecomputer/vscode-icons, MIT). update-pierre.sh
// fetches the sources and runs it.
//
//	go run fileicons/gen_pierre.go <pierre.json> <svgs-dir> <out-svg-dir>
package main

import (
	"encoding/json"
	"fmt"
	"go/format"
	"log"
	"maps"
	"os"
	"path/filepath"
	"slices"
	"strconv"
	"strings"
)

type themeColor struct {
	Dark  string      `json:"dark"`
	Light string      `json:"light"`
	FG    *themeColor `json:"fg"`
	BG    *themeColor `json:"bg"`
}

type themeEntry struct {
	Name           string      `json:"name"`
	SVGName        string      `json:"svgName"`
	Color          *themeColor `json:"color"`
	Opacity        float64     `json:"opacity"`
	FileExtensions []string    `json:"fileExtensions"`
	FileNames      []string    `json:"fileNames"`
}

type iconSpec struct {
	svg     string
	dark    string
	light   string
	bgDark  string
	bgLight string
	opacity float64
}

func main() {
	if len(os.Args) != 4 {
		log.Fatal("usage: go run fileicons/gen_pierre.go <pierre.json> <svgs-dir> <out-svg-dir>")
	}
	data, err := os.ReadFile(os.Args[1])
	if err != nil {
		log.Fatal(err)
	}
	var entries []themeEntry
	if err := json.Unmarshal(data, &entries); err != nil {
		log.Fatal(err)
	}
	svgSrcDir, svgOutDir := os.Args[2], os.Args[3]

	specs := map[string]iconSpec{}
	fileNames := map[string]string{}
	fileExts := map[string]string{}
	for _, e := range entries {
		svg := e.SVGName
		if svg == "" {
			svg = e.Name
		}
		sp := iconSpec{svg: svg, opacity: e.Opacity}
		if e.Color != nil {
			if e.Color.FG != nil && e.Color.BG != nil {
				sp.dark, sp.light = e.Color.FG.Dark, e.Color.FG.Light
				sp.bgDark, sp.bgLight = e.Color.BG.Dark, e.Color.BG.Light
			} else {
				sp.dark, sp.light = e.Color.Dark, e.Color.Light
			}
		}
		specs[e.Name] = sp
		for _, ext := range e.FileExtensions {
			low := strings.ToLower(ext)
			fileExts[low] = e.Name
			// Pierre lists dotless standard names like LICENSE under fileExtensions.
			if !strings.Contains(ext, ".") && ext == strings.ToUpper(ext) && ext != low {
				if _, exists := fileNames[low]; !exists {
					fileNames[low] = e.Name
				}
			}
		}
		for _, fn := range e.FileNames {
			fileNames[strings.ToLower(fn)] = e.Name
		}
	}

	usedIcons := map[string]bool{
		"file-duo":        true,
		"folder-duo":      true,
		"folder-open-duo": true,
	}
	for _, name := range fileNames {
		usedIcons[name] = true
	}
	for _, name := range fileExts {
		usedIcons[name] = true
	}

	if err := os.RemoveAll(svgOutDir); err != nil {
		log.Fatal(err)
	}
	if err := os.MkdirAll(svgOutDir, 0o755); err != nil {
		log.Fatal(err)
	}
	copied := map[string]bool{}
	for _, name := range slices.Sorted(maps.Keys(usedIcons)) {
		sp, ok := specs[name]
		if !ok {
			log.Fatalf("unknown icon %q", name)
		}
		if copied[sp.svg] {
			continue
		}
		b, err := os.ReadFile(filepath.Join(svgSrcDir, sp.svg+".svg"))
		if err != nil {
			log.Fatal(err)
		}
		if err := os.WriteFile(filepath.Join(svgOutDir, sp.svg+".svg"), b, 0o644); err != nil {
			log.Fatal(err)
		}
		copied[sp.svg] = true
	}

	var b strings.Builder
	b.WriteString("// Code generated by fileicons/gen_pierre.go from Pierre Icons (MIT); DO NOT EDIT.\n\npackage main\n\n")
	b.WriteString("var pierreIcons = map[string]pierreIconSpec{\n")
	for _, name := range slices.Sorted(maps.Keys(usedIcons)) {
		sp := specs[name]
		fmt.Fprintf(&b, "\t%q: {svg: %q", name, sp.svg)
		if sp.dark != "" {
			fmt.Fprintf(&b, ", dark: %q, light: %q", sp.dark, sp.light)
		}
		if sp.bgDark != "" {
			fmt.Fprintf(&b, ", bgDark: %q, bgLight: %q", sp.bgDark, sp.bgLight)
		}
		if sp.opacity > 0 && sp.opacity < 1 {
			fmt.Fprintf(&b, ", opacity: %s", strconv.FormatFloat(sp.opacity, 'g', -1, 64))
		}
		b.WriteString("},\n")
	}
	b.WriteString("}\n\n")

	b.WriteString("var pierreFileNames = map[string]string{\n")
	for _, fn := range slices.Sorted(maps.Keys(fileNames)) {
		fmt.Fprintf(&b, "\t%q: %q,\n", fn, fileNames[fn])
	}
	b.WriteString("}\n\n")

	b.WriteString("var pierreFileExts = map[string]string{\n")
	for _, ext := range slices.Sorted(maps.Keys(fileExts)) {
		fmt.Fprintf(&b, "\t%q: %q,\n", ext, fileExts[ext])
	}
	b.WriteString("}\n")

	src, err := format.Source([]byte(b.String()))
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("pierre_gen.go", src, 0o644); err != nil {
		log.Fatal(err)
	}
	fmt.Printf("wrote pierre_gen.go (%d icons, %d svgs, %d names, %d exts)\n",
		len(usedIcons), len(copied), len(fileNames), len(fileExts))
}
